export function wormholeLifetimeHours(name: string | null | undefined): number | null {
    if (!name) return null;
    return WORMHOLE_LIFETIME_HOURS[name.toUpperCase()] ?? null;
}

/** The shortest and longest life among some hole types, or null when none is known. */
export function lifetimeRange(names: readonly string[]): [number, number] | null {
    const hours = names.map(wormholeLifetimeHours).filter((value): value is number => value !== null);
    return hours.length ? [Math.min(...hours), Math.max(...hours)] : null;
}
