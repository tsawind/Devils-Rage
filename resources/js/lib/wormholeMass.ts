/** Total mass and max jump mass for a wormhole type name ("D845"), or null when unknown (K162, unset). */
export function wormholeMass(name: string | null | undefined): { total: number; maxJump: number } | null {
    const entry = name ? WORMHOLE_MASS[name.trim().toUpperCase()] : undefined;
    return entry ? { total: entry[0], maxJump: entry[1] } : null;
}
